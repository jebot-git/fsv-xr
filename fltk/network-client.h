#pragma once
#include "appearance.h"
#include "model.h"
#include <gio/gunixinputstream.h>
#include <gio/gunixoutputstream.h>
#include <fcntl.h>
#include <unistd.h>
#include <optional>
#include <deque>
#include <signal.h>

class NetworkClient {
  GSubprocess *child = nullptr;
  int input = -1, output = -1;
  std::string received, outgoing;
  std::deque<Json> events;
  struct Mount { std::filesystem::path path; std::string uri; };
  std::vector<Mount> mounts;
  std::chrono::steady_clock::time_point deadline;
public:
  ~NetworkClient() { cancel(); }
  bool busy() const { return child; }
  void cancel() {
    if (child) { g_subprocess_force_exit(child); g_object_unref(child); child = nullptr; }
    input = output = -1;
    std::fill(outgoing.begin(), outgoing.end(), '\0'); outgoing.clear(); received.clear(); events.clear();
  }
  void start(const std::string &uri, bool disconnect = false) {
    auto address = fsv::smbUri(uri);
    cancel();
    deadline = std::chrono::steady_clock::now() + std::chrono::seconds(120);
    std::error_code ec;
    auto adjacent = std::filesystem::read_symlink("/proc/self/exe", ec).parent_path() / "fsvr-network";
    auto helper = access(FSVR_NETWORK_HELPER, R_OK) == 0 ? std::string(FSVR_NETWORK_HELPER) : adjacent.string();
    GError *error = nullptr;
    child = g_subprocess_new(GSubprocessFlags(G_SUBPROCESS_FLAGS_STDIN_PIPE | G_SUBPROCESS_FLAGS_STDOUT_PIPE |
                                               G_SUBPROCESS_FLAGS_STDERR_SILENCE), &error,
                              "/usr/bin/python3", helper.c_str(), nullptr);
    if (!child) {
      auto message = std::string(error ? error->message : "Cannot start SMB service");
      g_clear_error(&error); throw std::runtime_error(message);
    }
    input = g_unix_input_stream_get_fd(G_UNIX_INPUT_STREAM(g_subprocess_get_stdout_pipe(child)));
    output = g_unix_output_stream_get_fd(G_UNIX_OUTPUT_STREAM(g_subprocess_get_stdin_pipe(child)));
    fcntl(input, F_SETFL, fcntl(input, F_GETFL) | O_NONBLOCK);
    fcntl(output, F_SETFL, fcntl(output, F_GETFL) | O_NONBLOCK);
    send(Json{{"command", disconnect ? "disconnect" : "connect"}, {"uri", address}});
  }
  void send(Json message) {
    if (!child) return;
    auto text = message.dump() + '\n';
    if (outgoing.size() + text.size() > 65536) throw std::runtime_error("SMB request too large");
    outgoing += text;
    std::fill(text.begin(), text.end(), '\0');
    if (message.contains("password") && message["password"].is_string()) {
      auto &password = message["password"].get_ref<std::string &>();
      std::fill(password.begin(), password.end(), '\0');
    }
  }
  std::optional<Json> poll() {
    if (!child) return {};
    if (std::chrono::steady_clock::now() >= deadline) {
      cancel(); throw std::runtime_error("SMB operation timed out; check the server and retry");
    }
    if (!outgoing.empty()) {
      // A helper may exit between polls; never deliver its pipe's SIGPIPE to
      // the renderer. Consume only a signal generated by this write.
      sigset_t blocked, previous, pending;
      sigemptyset(&blocked); sigaddset(&blocked, SIGPIPE);
      pthread_sigmask(SIG_BLOCK, &blocked, &previous);
      sigpending(&pending);
      auto n = write(output, outgoing.data(), outgoing.size());
      int savedError = errno;
      if (n < 0 && savedError == EPIPE && !sigismember(&pending, SIGPIPE)) {
        timespec zero{}; sigtimedwait(&blocked, nullptr, &zero);
      }
      pthread_sigmask(SIG_SETMASK, &previous, nullptr); errno = savedError;
      if (n > 0) { std::fill(outgoing.begin(), outgoing.begin() + n, '\0'); outgoing.erase(0, n); }
      else if (n < 0 && errno != EAGAIN && errno != EINTR) { cancel(); throw std::runtime_error("SMB service closed its input"); }
    }
    char bytes[8192];
    auto n = read(input, bytes, sizeof bytes);
    if (n > 0) received.append(bytes, n);
    if (received.size() > 1024 * 1024) { cancel(); throw std::runtime_error("SMB reply too large"); }
    for (auto split = received.find('\n'); split != std::string::npos; split = received.find('\n')) {
      events.push_back(Json::parse(received.substr(0, split))); received.erase(0, split + 1);
    }
    if (!events.empty()) {
      Json event = std::move(events.front()); events.pop_front();
      if (event.value("event", "") == "result") {
        if (event.value("kind", "") == "connected") {
          Mount mount{event.at("root_path").get<std::string>(), event.at("root_uri").get<std::string>()};
          mounts.erase(std::remove_if(mounts.begin(), mounts.end(), [&](auto &m) { return m.uri == mount.uri; }), mounts.end());
          mounts.push_back(std::move(mount));
        }
        cancel();
      }
      return event;
    }
    if (n == 0) { cancel(); throw std::runtime_error("SMB service exited without a reply; check its GIO runtime dependencies"); }
    return {};
  }
  std::string uriFor(const std::filesystem::path &path) const {
    for (auto &m : mounts) {
      auto relative = path.lexically_normal().lexically_relative(m.path);
      if (relative.empty() || *relative.begin() == "..") continue;
      auto uri = m.uri;
      for (auto &part : relative) {
        if (part == ".") continue;
        auto encoded = g_uri_escape_string(part.c_str(), nullptr, false);
        uri += "/" + std::string(encoded); g_free(encoded);
      }
      return uri;
    }
    return {};
  }
};
